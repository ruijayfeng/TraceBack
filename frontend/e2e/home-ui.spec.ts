/** Real backend/browser acceptance; no routes, response replacements or timers. */
import {test,expect} from '@playwright/test';
import {readFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
const output=path.resolve('../outputs/home_ui_checks');

test('overview metrics and charts lead the first screen; import is an accessible drawer',async({page})=>{
  await mkdir(output,{recursive:true});
  await page.setViewportSize({width:1440,height:900});await page.goto('/');
  await expect(page.getByRole('heading',{name:'安全运营态势总览',exact:true})).toBeVisible();
  const chart=page.getByRole('img',{name:'告警时间分布折线图'});
  await expect(chart).toBeVisible();
  expect((await chart.boundingBox())!.y).toBeLessThan(700);
  expect((await page.locator('.overview-metrics').boundingBox())!.y).toBeLessThan(350);
  await expect(page.getByLabel('选择告警文件')).toHaveCount(0);
  await expect(page.locator('.stage-run-panel')).toHaveCount(0);
  await expect(page.getByRole('region',{name:'历史分析任务'})).toHaveCount(0);
  await expect(page.getByRole('navigation',{name:'功能模块'}).getByRole('link')).toHaveCount(6);
  await page.screenshot({path:path.join(output,'home-desktop.png')});
  await page.getByRole('button',{name:'导入告警',exact:true}).click();
  const drawer=page.getByRole('dialog',{name:'导入告警与分析'});
  await expect(drawer).toBeVisible();await expect(drawer.getByLabel('选择告警文件')).toBeVisible();
  await expect(drawer.getByRole('button',{name:'开始分析'})).toBeDisabled();
  await page.screenshot({path:path.join(output,'import-drawer.png')});
  await page.keyboard.press('Escape');await expect(drawer).toHaveCount(0);
  await expect(page.getByRole('button',{name:'导入告警',exact:true})).toBeFocused();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:path.join(output,'home-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'导入告警',exact:true}).click();
  expect((await drawer.boundingBox())!.width).toBeLessThanOrEqual(390);
  expect(await drawer.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
  await page.screenshot({path:path.join(output,'import-mobile.png')});
});

test('closing during a real CLI run preserves the task and opens its actual overview result',async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const native=await readFile(path.resolve('../outputs/workbench_productization_checks/native.jsonl'));
  await page.goto('/');await expect(page.locator('.overview-metric').first()).toBeVisible();
  await page.getByRole('button',{name:'导入告警',exact:true}).click();
  const drawer=page.getByRole('dialog',{name:'导入告警与分析'});
  await drawer.getByLabel('选择告警文件').setInputFiles({name:'homepage-real-smoke.jsonl',mimeType:'application/octet-stream',buffer:native});
  await expect(drawer.getByText(/共 3 条 · 通过 3 条 · 失败 0 条 · 校验通过/)).toBeVisible();
  await page.screenshot({path:path.join(output,'import-validated.png')});
  const submitted=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname==='/api/v1/stage-runs');
  await drawer.getByRole('button',{name:'开始分析'}).click();
  const run=await submitted.then(r=>r.json());expect(run.status).toBe('QUEUED');
  await expect(drawer.locator('.run-details')).toHaveAttribute('data-run-id',run.run_id);
  await drawer.getByRole('button',{name:'关闭导入面板'}).click();
  await expect(drawer).toHaveCount(0);
  await expect(page.locator('.run-task-status')).toContainText('后台运行中');
  await expect(page.getByLabel('历史分析',{exact:true})).toHaveValue(run.run_id);
  await expect(page.locator('.overview-page')).toHaveAttribute('data-analysis-id',run.run_id);
  await expect(page.locator('.overview-metric').first().locator('strong')).toHaveText('3');
  expect(new URL(page.url()).searchParams.get('view')).toBe('overview');
  const completed=await request.get('/api/v1/stage-runs/'+run.run_id).then(r=>r.json());
  expect(completed.status).toBe('SUCCEEDED');expect(completed.exit_code).toBe(0);
  await page.getByRole('button',{name:'导入告警',exact:true}).click();
  await expect(drawer.locator('.run-details')).toHaveAttribute('data-run-id',run.run_id);
  await expect(drawer.getByRole('heading',{name:'分析成功',exact:true})).toBeVisible();
  await drawer.getByText('运行日志',{exact:true}).click();await expect(drawer.locator('.run-log')).toContainText('@@TRACEBACK_PROGRESS');
  await drawer.getByRole('button',{name:'关闭导入面板'}).click();
  await page.reload();await expect(page.locator('.overview-page')).toHaveAttribute('data-analysis-id',run.run_id);
  const previous=await request.get('/api/v1/stage-runs').then(r=>r.json()).then(v=>v.items.find((r:{input_count:number;result_available:boolean})=>r.input_count===2&&r.result_available));
  expect(previous).toBeTruthy();await page.getByLabel('历史分析',{exact:true}).selectOption(previous.run_id);
  await expect(page.locator('.overview-page')).toHaveAttribute('data-analysis-id',previous.run_id);
  await expect(page.locator('.overview-metric').first().locator('strong')).toHaveText('2');
  const previousSummary=await request.get('/api/v1/stage-analyses/'+previous.run_id+'/summary').then(r=>r.json());
  await expect(page.locator('.trend-meta')).toContainText(`共 ${previousSummary.summary.counts.kept_count} 条保留告警`);
  await page.getByRole('navigation',{name:'功能模块'}).getByRole('link',{name:'分析记录',exact:true}).click();
  const history=page.getByRole('region',{name:'历史分析任务'});await expect(history).toBeVisible();
  const failed=history.locator('tbody tr').filter({hasText:'smoke-intentional-failure.jsonl'}).first();
  await failed.getByRole('button',{name:'查看状态与日志'}).click();
  await expect(drawer.getByRole('heading',{name:'分析失败',exact:true})).toBeVisible();
  await expect(drawer.locator('.run-log')).toContainText('intentional CLI failure for UI diagnostics');
  await drawer.getByRole('button',{name:'关闭导入面板'}).click();
  await failed.getByRole('button',{name:'查看状态与日志'}).click();await expect(drawer.locator('.run-log')).toContainText('intentional CLI failure');
  await page.screenshot({path:path.join(output,'history-failure.png')});
  expect(errors).toEqual([]);
});
